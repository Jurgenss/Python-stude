"""
Тема 2. Задача 4. Анализ сезонности спроса по неделям

Дан список недельных объёмов продаж.
Нужно: среднее, отклонения, самая длинная серия «выше среднего»,
самый длинный спад «ниже среднего», интерпретация сезонности.

Метод: один проход, O(n).
"""


def analyze_seasonality(sales):
    """
    sales — список недельных объёмов продаж (числа)

    Возвращает словарь с результатами:
        avg           — среднее
        deviations    — список отклонений от среднего
        best_up       — (длина, начало, конец) самой длинной серии выше среднего
        best_down     — (длина, начало, конец) самой длинной серии ниже среднего
    """
    n = len(sales)
    if n == 0:
        return None

    avg = sum(sales) / n
    deviations = [s - avg for s in sales]

    best_up = (0, -1, -1)      # (длина, начало, конец)
    best_down = (0, -1, -1)

    up_len = 0
    up_start = 0
    down_len = 0
    down_start = 0

    for i, s in enumerate(sales):
        if s > avg:
            if up_len == 0:
                up_start = i
            up_len += 1
            if up_len > best_up[0]:
                best_up = (up_len, up_start, i)
            down_len = 0
        elif s < avg:
            if down_len == 0:
                down_start = i
            down_len += 1
            if down_len > best_down[0]:
                best_down = (down_len, down_start, i)
            up_len = 0
        else:                  # ровно среднее — разрывает обе серии
            up_len = 0
            down_len = 0

    return {
        'avg': avg,
        'deviations': deviations,
        'best_up': best_up,
        'best_down': best_down,
    }


def print_report(title, sales):
    print(f"=== {title} ===")
    print(f"Продажи по неделям: {sales}")

    result = analyze_seasonality(sales)
    if result is None:
        print("  Пустой список — анализировать нечего.\n")
        return

    avg = result['avg']
    print(f"Среднее: {avg:.2f}")
    print(f"{'Неделя':>7} {'Продажи':>9} {'Отклонение':>12} {'Выше/ниже':>12}")
    for i, (s, d) in enumerate(zip(sales, result['deviations'])):
        mark = 'выше' if d > 0 else ('ниже' if d < 0 else 'равно')
        print(f"{i:>7} {s:>9} {d:>+12.2f} {mark:>12}")

    up_len, up_start, up_end = result['best_up']
    down_len, down_start, down_end = result['best_down']

    if up_len > 0:
        print(f"\n  Самая длинная серия ВЫШЕ среднего: длина {up_len}, "
              f"недели {up_start}..{up_end}")
    else:
        print(f"\n  Серий ВЫШЕ среднего нет.")

    if down_len > 0:
        print(f"  Самая длинная серия НИЖЕ среднего: длина {down_len}, "
              f"недели {down_start}..{down_end}")
    else:
        print(f"  Серий НИЖЕ среднего нет.")

    # интерпретация сезонности
    # критерий: длина серии >= 25% от n — говорим о выраженной сезонности
    threshold = max(2, n // 4)
    if up_len >= threshold or down_len >= threshold:
        print(f"\n  Вывод: сезонность ВЫРАЖЕНА — есть продолжительные периоды "
              f"подъёма/спада (длина >= {threshold}).")
    else:
        print(f"\n  Вывод: сезонность СЛАБАЯ — колебания вокруг среднего "
              f"не образуют длинных серий (порог {threshold}).")
    print()


# ---------------------------------------------------------------
# 1) Нормальный набор: выраженная сезонность (рост-спад-рост)
# ---------------------------------------------------------------
sales_1 = [100, 120, 140, 160, 180, 160, 140, 120, 100, 80, 60, 80]
print_report("Нормальный набор (выраженная сезонность)", sales_1)


# ---------------------------------------------------------------
# 2) Граничный набор: ровно половина выше, половина ниже
# ---------------------------------------------------------------
sales_2 = [10, 10, 10, 30, 30, 30]
print_report("Граничный набор (половина выше, половина ниже)", sales_2)


# ---------------------------------------------------------------
# 3) Особый набор: все значения равны — отклонений нет
# ---------------------------------------------------------------
sales_3 = [50, 50, 50, 50, 50]
print_report("Особый набор (все продажи равны)", sales_3)


# ---------------------------------------------------------------
# 4) Особый набор: монотонный рост — все недели выше среднего, кроме первой
# ---------------------------------------------------------------
sales_4 = [10, 20, 30, 40, 50, 60, 70]
print_report("Особый набор (монотонный рост)", sales_4)


"""
Формализация:

    sales = [s0, s1, ..., s_{n-1}].
    avg = (сумма s_i) / n.
    d_i = s_i - avg.
    «Выше» = d_i > 0, «ниже» = d_i < 0, «равно» = d_i == 0.
    Ищем максимальную длину непрерывной серии d_i > 0 и d_i < 0.

Алгоритм:

    Один проход. Поддерживаем текущую длину серии вверх (up_len)
    и вниз (down_len), их начала. При смене знака — сбрасываем
    противоположный счётчик. Обновляем лучшую длину и её границы.
    Равное среднему значение разрывает обе серии.

Оценка сложности:

    Время: O(n) — один проход.
    Память: O(n) для списка отклонений (можно O(1), если не хранить).
    Класс: линейный.

Результаты (примерно):

1) Нормальный (12 недель, сезонность):
   Среднее 120. Выше среднего: недели 1..4 (120,140,160,180) — длина 4.
   Ниже среднего: недели 8..10 (120,100,80,60) — длина 4.
   Сезонность выражена.

2) Граничный [10,10,10,30,30,30]:
   Среднее 20. Первые 3 недели ниже (10<20), последние 3 выше (30>20).
   Обе серии длины 3.

3) Особый [50,50,50,50,50]:
   Все равны среднему → отклонения 0, серий нет. Сезонности нет.

4) Особый [10,20,30,40,50,60,70]:
   Среднее 40. Выше: 50,60,70 (недели 4..6) — длина 3.
   Ниже: 10,20,30 (недели 0..2) — длина 3. Неделя 3 = 40 (равно).
   Тренд роста, но не «сезонность» в строгом смысле.

Интерпретация:

    Сезонность считается выраженной, если длина самой длинной серии
    «выше» или «ниже» среднего не меньше 25% от числа недель.
    Порог эвристический; в отчёте его нужно обосновать.
"""