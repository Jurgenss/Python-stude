"""
Тема 2. Задача 3. Модель спроса и предложения:
поиск равновесной цены дискретным перебором

Дано: таблица «цена — спрос — предложение».
Нужно: найти цену с минимальной |спрос - предложение|,
определить наличие точного равенства, охарактеризовать рынок
для каждой цены (дефицит / избыток / равновесие).

Метод: один проход по таблице, O(n).
"""


def find_equilibrium(table):
    """
    table — список кортежей (цена, спрос, предложение)

    Возвращает:
        best_price, best_demand, best_supply — цена с минимальной |разницей|
        min_diff      — минимальная |разница|
        exact_price   — цена точного равенства (или None)
        market_state  — список (цена, разница, состояние)
    """
    min_diff = float('inf')
    best_price = best_demand = best_supply = None
    exact_price = None
    market_state = []

    for price, demand, supply in table:
        diff = demand - supply
        abs_diff = abs(diff)

        if diff == 0:
            exact_price = price

        if abs_diff < min_diff:
            min_diff = abs_diff
            best_price, best_demand, best_supply = price, demand, supply

        if diff > 0:
            state = 'дефицит'
        elif diff < 0:
            state = 'избыток'
        else:
            state = 'равновесие'
        market_state.append((price, diff, state))

    return best_price, best_demand, best_supply, min_diff, exact_price, market_state


def print_report(title, table):
    print(f"=== {title} ===")
    print(f"{'Цена':>6} {'Спрос':>8} {'Предложение':>13} {'Разница':>9} {'Рынок':>13}")
    for price, demand, supply in table:
        diff = demand - supply
        if diff > 0:
            state = 'дефицит'
        elif diff < 0:
            state = 'избыток'
        else:
            state = 'равновесие'
        print(f"{price:>6} {demand:>8} {supply:>13} {diff:>+9} {state:>13}")

    best_price, best_demand, best_supply, min_diff, exact_price, _ = find_equilibrium(table)
    print(f"\n  Равновесная цена (мин. |разница|): {best_price}")
    print(f"    спрос = {best_demand}, предложение = {best_supply}, |разница| = {min_diff}")
    if exact_price is not None:
        print(f"  Точное равенство: есть, при цене {exact_price}")
    else:
        print(f"  Точное равенство: нет")
    print()


# ---------------------------------------------------------------
# 1) Нормальный набор: есть точное равенство
# ---------------------------------------------------------------
table_1 = [
    (10, 100, 20),
    (20, 80, 40),
    (30, 60, 60),   # равновесие
    (40, 40, 80),
    (50, 20, 100),
]
print_report("Нормальный набор (есть точное равенство)", table_1)


# ---------------------------------------------------------------
# 2) Граничный набор: равенства нет, минимальная разница = 2
# ---------------------------------------------------------------
table_2 = [
    (10, 100, 20),
    (20, 80, 40),
    (30, 62, 60),   # разница +2
    (40, 40, 80),
    (50, 20, 100),
]
print_report("Граничный набор (равенства нет, мин. разница = 2)", table_2)


# ---------------------------------------------------------------
# 3) Особый набор: везде дефицит (спрос > предложение)
# ---------------------------------------------------------------
table_3 = [
    (10, 200, 20),
    (20, 180, 40),
    (30, 150, 60),
    (40, 120, 80),
    (50, 100, 100),   # единственное равенство — на границе
]
# Чтобы сделать «везде дефицит», заменим последнюю строку:
table_3 = [
    (10, 200, 20),
    (20, 180, 40),
    (30, 150, 60),
    (40, 120, 80),
    (50, 100, 90),
]
print_report("Особый набор (везде дефицит, равенства нет)", table_3)


"""
Формализация:

    Таблица: (price_i, demand_i, supply_i) для i = 1..n.
    Разница: diff_i = demand_i - supply_i.
    Равновесная цена: price_i с минимальным |diff_i|.
    Точное равновесие: price_i, где diff_i = 0.
    Характер рынка:
        diff_i > 0 — дефицит (спрос больше предложения);
        diff_i < 0 — избыток (предложение больше спроса);
        diff_i = 0 — равновесие.

Алгоритм:

    Один проход по таблице.
    Для каждой строки считаем diff, |diff|, обновляем минимум,
    фиксируем точное равенство (если есть), записываем состояние рынка.

Оценка сложности:

    Время: O(n) — один проход по таблице из n строк.
    Память: O(n) для списка состояний (или O(1), если выводить на лету).
    Класс: линейный.

Результаты:

1) Нормальный набор:
   равновесная цена = 30 (спрос = 60, предложение = 60, разница 0).
   Точное равенство есть при цене 30.
   До 30 — дефицит (10, 20), после 30 — избыток (40, 50).

2) Граничный набор:
   равновесная цена = 30 (спрос = 62, предложение = 60, |разница| = 2).
   Точного равенства нет. Минимальная разница — 2.
   Характер рынка: до 30 — дефицит, после 30 — избыток.

3) Особый набор:
   равновесная цена = 50 (спрос = 100, предложение = 90, |разница| = 10).
   Точного равенства нет. Везде дефицит (спрос > предложение).

Ограничение метода:

    Дискретный перебор находит равновесие только среди заданных цен.
    Если истинная равновесная цена лежит между табличными значениями
    (например, 25 при ценах 20 и 30), перебор её не обнаружит —
    нужна интерполяция или аналитическая модель спроса/предложения.
"""