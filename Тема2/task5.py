# ---------------------------------------------------------------
need_2 = [1, 1, 1, 1, 1, 1, 1, 1]          # нужно по 1 человеку каждый час
employees_2 = [
    [(0, 4)],                # С0
    [(4, 8)],                # С1
    [(0, 8)],                # С2 — может закрыть всё один
]
