print_report("Нормальный набор (10 сотрудников)", need_4, employees_4)


"""
Формализация:

    Часы h = 0..H-1.
    need[h] — потребность в час h.
    Для сотрудника i: S_i — множество допустимых смен; смена s = (start, end)
    покрывает часы start, start+1, ..., end-1.
    Переменная x_i ∈ S_i ∪ {None} — выбранная смена сотрудника i.
    Ограничение: для каждого h: |{i : x_i покрывает h}| >= need[h].
    Цель: min |{i : x_i != None}|.

Алгоритм:

    Полный перебор декартова произведения вариантов:
        options_i = [None] + list(S_i)
        для каждой комбинации (x_0, ..., x_{m-1}) из product(options_0, ..., options_{m-1}):
            посчитать coverage[h], workers;
            если coverage[h] >= need[h] для всех h и workers < best:
                обновить best.
    Вернуть лучшую комбинацию.

Оценка сложности:

    Пусть k — среднее число смен у сотрудника, m — число сотрудников.
    Число комбинаций: (1 + k)^m.
    Для m = 10, k = 2: 3^10 = 59 049 — быстро.
    Для m = 12, k = 3: 4^12 = 16 777 216 — заметно, но приемлемо.
    Время: O((1+k)^m * m * H) — на каждую комбинацию проверяем m сотрудников
        и H часов.
    Память: O(H) для coverage + O(m) для назначения.
    Класс: экспоненциальный по числу сотрудников m.

Результаты (примерно):

1) Нормальный (5 сотрудников):
   Минимум работающих — 3 (например, С2 на (0,6), С3 на (2,6),
   С4 на (0,8) — покрытие проверяется). Точное назначение зависит
   от перебора; в отчёте привести фактическое.

2) Граничный (3 сотрудника, нужно по 1):
   Достаточно 1 сотрудника С2 на (0,8) — покрывает все часы.
   Минимум работающих = 1.

3) Особый (3 сотрудника, нужно по 3):
   Максимальное покрытие в час — 3 (все три смены), но в часы 0-3
   работают только С0 и С2 (2 человека), а нужно 3 → покрытие
   невозможно. Возвращается (None, None, None).

4) Нормальный (10 сотрудников):
   Минимум работающих — зависит от данных; перебор найдёт оптимум.
   При 3^10 = 59 049 комбинациях работает быстро (доли секунды).

Интерпретация:

    Перебор даёт ГАРАНТИРОВАННО оптимальное решение по числу работающих,
    но экспоненциально зависит от m. Для m > 15-20 нужны другие методы:
    целочисленное линейное программирование, жадные эвристики,
    динамическое программирование по часам.
"""