"""
Тема 2. Задача 5. Планирование смен и покрытие потребности в персонале

Дано:
    need[h] — потребность в работниках в час h (h = 0..H-1).
    employees[i] — список допустимых смен сотрудника i;
                   смена = (start, end), работает в часы start..end-1.

Нужно:
    выбрать каждому сотруднику смену (или «не работать») так, чтобы
    в каждый час покрытие >= need[h], а число работающих было минимальным.

Метод: полный перебор декартова произведения вариантов (itertools.product).
"""

import itertools


def covers(shift, h):
    """Покрывает ли смена shift час h."""
    if shift is None:
        return False
    start, end = shift
    return start <= h < end


def evaluate(assignment, need):
    """
    assignment — список смен (или None) для каждого сотрудника.
    Возвращает (ok, coverage, workers):
        ok       — покрытие >= need во все часы;
        coverage — список покрытия по часам;
        workers  — число работающих.
    """
    H = len(need)
    coverage = [0] * H
    workers = 0
    for shift in assignment:
        if shift is not None:
            workers += 1
            for h in range(H):
                if covers(shift, h):
                    coverage[h] += 1
    ok = all(coverage[h] >= need[h] for h in range(H))
    return ok, coverage, workers


def plan_shifts(need, employees):
    """
    need      — список потребностей по часам.
    employees — список списков допустимых смен для каждого сотрудника.

    Возвращает (best_assignment, best_coverage, best_workers)
    или (None, None, None), если покрытие невозможно.
    """
    m = len(employees)
    # варианты для каждого сотрудника: None (не работать) + его смены
    options_per_employee = [[None] + list(shifts) for shifts in employees]

    best_assignment = None
    best_coverage = None
    best_workers = float('inf')

    total_combinations = 1
    for opts in options_per_employee:
        total_combinations *= len(opts)

    for assignment in itertools.product(*options_per_employee):
        ok, coverage, workers = evaluate(assignment, need)
        if not ok:
            continue
        if workers < best_workers:
            best_workers = workers
            best_assignment = assignment
            best_coverage = coverage

    if best_assignment is None:
        return None, None, None
    return best_assignment, best_coverage, best_workers


def print_report(title, need, employees):
    print(f"=== {title} ===")
    H = len(need)
    print(f"Потребность по часам ({H} ч): {need}")
    print(f"Сотрудников: {len(employees)}")
    for i, shifts in enumerate(employees):
        print(f"  Сотрудник {i}: смены {shifts}")
    print()

    assignment, coverage, workers = plan_shifts(need, employees)
    if assignment is None:
        print("  Покрытие невозможно при данных сменах.\n")
        return

    print(f"  Минимальное число работающих: {workers}")
    print("  Назначение смен:")
    for i, shift in enumerate(assignment):
        label = "не работает" if shift is None else f"смена {shift}"
        print(f"    Сотрудник {i}: {label}")

    print("  Покрытие по часам (покрытие / потребность):")
    for h in range(H):
        mark = "OK" if coverage[h] >= need[h] else "НЕДОБОР"
        print(f"    Час {h}: {coverage[h]} / {need[h]}  [{mark}]")
    print()


# ---------------------------------------------------------------
# 1) Нормальный набор: потребность 2-3 человека, 5 сотрудников
# ---------------------------------------------------------------
need_1 = [2, 2, 3, 3, 2, 2, 1, 1]          # 8 часов
employees_1 = [
    [(0, 4), (4, 8)],        # С0: утро или вечер
    [(0, 4), (4, 8)],        # С1
    [(0, 6), (2, 8)],        # С2
    [(2, 6)],                # С3
    [(0, 8)],                # С4: полный день
]
print_report("Нормальный набор (5 сотрудников)", need_1, employees_1)


# ---------------------------------------------------------------
