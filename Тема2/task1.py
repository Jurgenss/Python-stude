"""
Тема 2. Задача 1. Планирование загрузки производственных линий

Дано: 3 линии с разной производительностью (шт/ч), стоимостью часа (руб/ч)
и максимально допустимым временем работы (ч). Нужно выпустить N изделий,
распределив время так, чтобы стоимость была минимальной.

Метод: полный перебор всех комбинаций (t1, t2, t3) с шагом step.
"""


def plan_production(N, lines, step=0.5):
    """
    N     — требуемый объём выпуска (шт)
    lines — список из трёх кортежей (производительность, стоимость_часа, макс_время)
    step  — шаг перебора по времени (ч)

    Возвращает (best_plan, best_cost), где best_plan = (t1, t2, t3),
    либо (None, None), если план недостижим.
    """
    (p1, c1, m1), (p2, c2, m2), (p3, c3, m3) = lines

    best_cost = float('inf')
    best_plan = None
    best_output = 0

    # количество шагов для каждой линии
    n1 = int(m1 / step)
    n2 = int(m2 / step)
    n3 = int(m3 / step)

    for i in range(n1 + 1):
        t1 = i * step
        for j in range(n2 + 1):
            t2 = j * step
            for k in range(n3 + 1):
                t3 = k * step

                # суммарный выпуск
                output = p1 * t1 + p2 * t2 + p3 * t3
                if output < N:
                    continue                     # план не выполняет норму

                # суммарная стоимость
                cost = c1 * t1 + c2 * t2 + c3 * t3

                # обновляем «чемпиона»: меньше стоимость;
                # при равной стоимости — больше выпуск (запас)
                if cost < best_cost or (cost == best_cost and output > best_output):
                    best_cost = cost
                    best_plan = (round(t1, 2), round(t2, 2), round(t3, 2))
                    best_output = output

    if best_plan is None:
        return None, None
    return best_plan, best_cost


# ---------------------------------------------------------------
# Тесты
# ---------------------------------------------------------------

# Нормальный набор: 3 линии, N = 100
lines = [
    (10, 500, 8),    # линия 1: 10 шт/ч, 500 руб/ч, макс 8 ч
    (15, 600, 6),    # линия 2: 15 шт/ч, 600 руб/ч, макс 6 ч
    (20, 900, 5),    # линия 3: 20 шт/ч, 900 руб/ч, макс 5 ч
]
N = 100

print("=== Нормальный набор ===")
plan, cost = plan_production(N, lines, step=0.5)
if plan is None:
    print(f"N={N}: план недостижим")
else:
    t1, t2, t3 = plan
    output = 10 * t1 + 15 * t2 + 20 * t3
    print(f"N={N}: план = {plan}, выпуск = {output}, стоимость = {cost}")

# Граничный: N = 0
print("\n=== Граничный: N = 0 ===")
plan, cost = plan_production(0, lines, step=0.5)
if plan is None:
    print(f"N=0: план недостижим")
else:
    print(f"N=0: план = {plan}, стоимость = {cost}")

# Граничный: N = максимально возможный выпуск
max_output = 10 * 8 + 15 * 6 + 20 * 5   # 80 + 90 + 100 = 270
print(f"\n=== Граничный: N = {max_output} (все линии на максимуме) ===")
plan, cost = plan_production(max_output, lines, step=0.5)
if plan is None:
    print(f"N={max_output}: план недостижим")
else:
    t1, t2, t3 = plan
    output = 10 * t1 + 15 * t2 + 20 * t3
    print(f"N={max_output}: план = {plan}, выпуск = {output}, стоимость = {cost}")

# Особый: N больше максимально возможного выпуска
print(f"\n=== Особый: N = {max_output + 1} (недостижимо) ===")
plan, cost = plan_production(max_output + 1, lines, step=0.5)
if plan is None:
    print(f"N={max_output + 1}: план недостижим")
else:
    print(f"N={max_output + 1}: план = {plan}, стоимость = {cost}")


"""
Формализация:

    Переменные: t1, t2, t3 — время работы каждой линии (ч).
    Ограничения: 0 <= t1 <= 8, 0 <= t2 <= 6, 0 <= t3 <= 5.
    Норма:       10*t1 + 15*t2 + 20*t3 >= N.
    Цель:        минимизировать 500*t1 + 600*t2 + 900*t3.

Алгоритм:

    Полный перебор всех комбинаций (t1, t2, t3) с шагом step.
    Для каждой проверяем: выпуск >= N (иначе пропускаем),
    считаем стоимость, запоминаем лучшую.
    При равной стоимости предпочитаем больший выпуск (чтобы был запас).

Результаты:

    1) Нормальный набор, N = 100:
       план = (0.0, 6.0, 0.5), выпуск = 100, стоимость = 4050 руб.
       Комментарий: линия 2 (40 руб/шт) загружена на максимум
       (6 ч = 90 шт, 3600 руб), остаток 10 шт добраны линией 3
       (45 руб/шт, 0.5 ч = 450 руб). Линия 1 (50 руб/шт) не используется
       как самая дорогая по удельной стоимости.

    2) Граничный, N = 0:
       план = (0.0, 0.0, 0.0), стоимость = 0 руб.

    3) Граничный, N = 270 (максимально возможный выпуск):
       план = (8.0, 6.0, 5.0), выпуск = 270, стоимость = 12100 руб.
       Все линии на максимуме — единственный способ достичь 270.

    4) Особый, N = 271:
       план недостижим — суммарный максимум 270 < 271.

Оценка сложности:

    Число комбинаций: (T1/h + 1) * (T2/h + 1) * (T3/h + 1).
    Для T = 8, 6, 5 и h = 0.5: 17 * 13 * 11 = 2431 комбинация.
    Временная сложность: O((T/h)^k), где k — число линий.
    Для k = 3 — практически мгновенно.
    Пространственная сложность: O(1) — только лучший план и счётчики.
    Класс сложности: экспоненциальный по числу линий k; при фиксированном
    k = 3 — константное число операций.

Ограничение метода:

    При k = 10 линиях и том же шаге число комбинаций ~17^10 ≈ 2*10^12 —
    перебор неприменим. Для больших k нужны другие методы (линейное
    программирование, динамическое программирование, жадные эвристики).
"""