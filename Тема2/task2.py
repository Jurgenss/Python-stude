"""
Тема 2. Задача 2. Распределение товара по складам

Дано: склады с остатками товара, магазины с заявками.
Нужно: распределить запасы, максимизируя суммарный удовлетворённый спрос.

Метод: жадный алгоритм. Магазины обслуживаются по порядку; каждому
выдаётся товар с доступных складов (тоже по порядку), пока заявка
не удовлетворена или не кончатся запасы.
"""


def distribute_goods(warehouses, shops):
    """
    warehouses — список кортежей (имя_склада, остаток)
    shops      — список кортежей (имя_магазина, заявка)

    Возвращает:
        plan           — {магазин: [(склад, количество), ...]}
        total_served   — всего удовлетворено (шт)
        total_shortage — всего дефицит (шт)
        stock_left     — остатки складов после распределения
    """
    # копия остатков, чтобы не портить исходные данные
    stock = {name: amount for name, amount in warehouses}
    plan = {}
    total_served = 0
    total_shortage = 0

    for shop_name, demand in shops:
        need = demand
        deliveries = []

        for wh_name in stock:              # порядок складов — как в словаре
            if need == 0:
                break
            take = min(need, stock[wh_name])
            if take > 0:
                deliveries.append((wh_name, take))
                stock[wh_name] -= take
                need -= take

        served = demand - need
        plan[shop_name] = deliveries
        total_served += served
        total_shortage += need

    return plan, total_served, total_shortage, stock


def print_result(title, plan, served, shortage, stock_left):
    print(f"=== {title} ===")
    for shop, deliveries in plan.items():
        if deliveries:
            parts = ", ".join(f"{wh}: {qty}" for wh, qty in deliveries)
            print(f"  {shop} получил: {parts}")
        else:
            print(f"  {shop} получил: ничего")
    print(f"  Итого удовлетворено: {served}")
    print(f"  Итого дефицит:       {shortage}")
    print(f"  Остатки складов:     {stock_left}")
    print()


# ---------------------------------------------------------------
# 1) Нормальный набор: запасов хватает
# ---------------------------------------------------------------
warehouses_1 = [("С1", 50), ("С2", 30), ("С3", 80)]   # всего 160
shops_1      = [("М1", 60), ("М2", 40), ("М3", 50)]   # спрос 150

plan, served, shortage, stock_left = distribute_goods(warehouses_1, shops_1)
print_result("Нормальный набор (запасов хватает)", plan, served, shortage, stock_left)


# ---------------------------------------------------------------
# 2) Граничный набор: запасов ровно столько, сколько спрос
# ---------------------------------------------------------------
warehouses_2 = [("С1", 50), ("С2", 50), ("С3", 50)]   # всего 150
shops_2      = [("М1", 60), ("М2", 40), ("М3", 50)]   # спрос 150

plan, served, shortage, stock_left = distribute_goods(warehouses_2, shops_2)
print_result("Граничный набор (запасы = спрос)", plan, served, shortage, stock_left)


# ---------------------------------------------------------------
# 3) Особый набор: запасов меньше спроса — дефицит
# ---------------------------------------------------------------
warehouses_3 = [("С1", 30), ("С2", 20), ("С3", 30)]   # всего 80
shops_3      = [("М1", 60), ("М2", 40), ("М3", 50)]   # спрос 150

plan, served, shortage, stock_left = distribute_goods(warehouses_3, shops_3)
print_result("Особый набор (запасов меньше спроса)", plan, served, shortage, stock_left)


"""
Формализация:

    Склады: W = {С1, С2, С3} с остатками stock[w].
    Магазины: S = {М1, М2, М3} с заявками demand[s].
    Переменные: x[s][w] — сколько магазин s получил со склада w.
    Ограничения:
        сумма_w x[s][w] <= demand[s]        (не больше заявки)
        сумма_s x[s][w] <= stock[w]         (не больше остатка склада)
        x[s][w] >= 0
    Цель: максимизировать сумму_s сумма_w x[s][w]
          (эквивалентно: минимизировать суммарный дефицит).

Алгоритм (жадный):

    Для каждого магазина s (в порядке списка):
        need = demand[s]
        Для каждого склада w (в порядке списка):
            take = min(need, stock[w])
            x[s][w] = take
            stock[w] -= take
            need -= take
            если need == 0 — прервать внутренний цикл
        дефицит[s] = need

    Сложность: O(m * w) — для каждого из m магазинов проходим по w складам.
    Память: O(m * w) для плана (в худшем случае) или O(w) для остатков.

Результаты:

1) Нормальный набор (С1=50, С2=30, С3=80; спрос 150):
   М1: С1: 50, С2: 10
   М2: С2: 20, С3: 20
   М3: С3: 50
   Удовлетворено: 150, дефицит 0, остатки: С1=0, С2=0, С3=10.

2) Граничный набор (С1=С2=С3=50; спрос 150):
   М1: С1: 50, С2: 10
   М2: С2: 40
   М3: С3: 50
   Удовлетворено: 150, дефицит 0, остатки: все нули.
   Запасы израсходованы ровно под спрос.

3) Особый набор (С1=30, С2=20, С3=30; спрос 150):
   М1: С1: 30, С2: 20, С3: 10
   М2: С3: 20 (дефицит 20)
   М3: ничего (дефицит 50)
   Удовлетворено: 80, дефицит 70, остатки: все нули.

Оценка сложности:

    Временная: O(m * w), где m — число магазинов, w — число складов.
        Для m = w = 3: 9 итераций внутреннего цикла.
    Пространственная: O(m * w) для плана (худший случай — каждый магазин
        получает от каждого склада); O(w) для остатков.
    Класс сложности: линейный по размеру входа (m * w), если считать
        размером входа таблицу «магазины × склады». Квадратичный, если
        m ≈ w.

Свойства жадного алгоритма:

    - Суммарный удовлетворённый спрос НЕ зависит от порядка магазинов,
      если товара хватает (все получают полностью) или если считать
      сумму в штуках при дефиците (сколько всего отдано — одинаково).
    - Порядок магазинов влияет на РАСПРЕДЕЛЕНИЕ при дефиците:
      первые в очереди получают больше. Это «несправедливость» жадного
      подхода — её можно исправить, сортируя магазины по приоритету
      (например, по убыванию заявки).
    - Порядок складов влияет на то, какой склад отдаёт товар, но не
      на суммарные показатели.
"""