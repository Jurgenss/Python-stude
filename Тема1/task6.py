

def multiply_matrices(A, B):
    n = len(A)
    m = len(A[0])
    k = len(B[0])

    if len(B) != m:
        return None

    C = [[0] * k for _ in range(n)]

    for i in range(n):
        for j in range(k):
            for t in range(m):
                C[i][j] += A[i][t] * B[t][j]


    return C            








A = [[1, 2],
     [3, 4]]
B = [[5, 6],
     [7, 8]]
print(multiply_matrices(A, B))
# ожидаем [[19, 22], [43, 50]]




# A: 2×3, B: 3×2  → результат 2×2
A = [[1, 2, 3],
     [4, 5, 6]]
B = [[7, 8],
     [9, 10],
     [11, 12]]
print(multiply_matrices(A, B))
# ожидаем [[58, 64], [139, 154]]

# A: 3×2, B: 2×4  → результат 3×4
A = [[1, 2],
     [3, 4],
     [5, 6]]
B = [[1, 2, 3, 4],
     [5, 6, 7, 8]]
print(multiply_matrices(A, B))
# ожидаем [[11, 14, 17, 20],
#          [23, 30, 37, 44],
#          [35, 46, 57, 68]]



