def conditional_nested_loop(s):
    n = len(s)
    operations = 0
    for i in range(n):
        if s[i] % 2 == 0:
            for j in range(i + 1, n):
                operations += 1
    return operations                










print(conditional_nested_loop([2, 4, 6, 8, 10]))   # все чётные, n=5
print(conditional_nested_loop([1, 3, 5, 7, 9]))    # все нечётные, n=5
print(conditional_nested_loop([1, 2, 3, 4, 5, 6])) # половина чётных, n=6





