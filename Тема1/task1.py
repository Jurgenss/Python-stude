
arr =[10,20,30,40,50]


def linear_search(arr , x):
    comparions = 0
    for i in range(len(arr)):
        comparions +=1
        if arr[i] == x:
            return i, comparions

    return -1, comparions    



print(linear_search(arr, 10))
print(linear_search(arr, 50))
print(linear_search(arr, 99))


"""
Результаты:
(0, 1)   # x = 10 — первый элемент
(4, 5)   # x = 50 — последний элемент
(-1, 5)  # x = 99 — отсутствует

Оценка сложности:
- Лучший случай:   O(1)  — элемент на первом месте, 1 сравнение.
- Худший случай:   O(n)  — элемента нет или он последний, n сравнений.
- Средний случай:  O(n)  — примерно (n+1)/2 сравнений, константа 1/2 отбрасывается.
- Временная сложность:       O(n) — линейная.
- Пространственная сложность: O(1) — только счётчик, индекс и кортеж; память не зависит от n.
- Класс сложности: линейный.
"""