
def remove_duplicates_v1(numbers):
    seen = set()
    result = []
    for x in numbers:
        if x not in seen:
            result.append(x)
            seen.add(x)
    return result        




def remove_duplicates_v2(numbers):
    seen = set()
    result = []
    for x in numbers:
        before = len(seen)
        seen.add(x)
        if len(seen) > before:
            result.append(x)
    return result        




data = [1, 2, 2, 3, 1, 4, 3, 5]
print(remove_duplicates_v1(data))   # ожидаем [1, 2, 3, 4, 5]
print(remove_duplicates_v2(data))   # ожидаем [1, 2, 3, 4, 5]

print(remove_duplicates_v1([1, 1, 1, 1]))   # [1]
print(remove_duplicates_v2([1, 1, 1, 1]))   # [1]

print(remove_duplicates_v1([]))             # []
print(remove_duplicates_v2([]))             # []

print(remove_duplicates_v1([5, 4, 3, 2, 1]))  # [5, 4, 3, 2, 1]
print(remove_duplicates_v2([5, 4, 3, 2, 1]))  # [5, 4, 3, 2, 1]



