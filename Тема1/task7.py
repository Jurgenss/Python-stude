def generate_subsets(elements):
    n = len(elements)
    all_Subsets = []
    operations = 0

    for mask in range(2 ** n):            # 0, 1, 2, 3, ..., 2^n - 1
        subset = []
        for t in range(n):
            operations += 1
            if mask & (1 << t):                 # это 2^t: для t=0 → 1 (001), t=1 → 2 (010), t=2 → 4 (100)  # ненулевой результат → бит t установлен в mask
                subset.append(elements[t])
        all_Subsets.append(subset)
    return all_Subsets, operations            







print(generate_subsets(['a', 'b']))
print(generate_subsets(['a', 'b', 'c']))
print(generate_subsets(['a', 'b', 'c', 'd']))






